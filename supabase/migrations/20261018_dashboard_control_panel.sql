-- Owner-controlled dashboard access and safe manual sync controls.
-- Run this migration in the Ponyo Supabase project before enabling dashboard writes.

create table if not exists public.dashboard_access (
  email text primary key,
  permissions text[] not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by text not null
);
alter table public.dashboard_access enable row level security;
revoke all on public.dashboard_access from anon, authenticated;

create table if not exists public.dashboard_audit_log (
  id bigint generated by default as identity primary key,
  actor_email text not null,
  action text not null,
  target_email text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_dashboard_audit_created_at
  on public.dashboard_audit_log(created_at desc);
alter table public.dashboard_audit_log enable row level security;
revoke all on public.dashboard_audit_log from anon, authenticated;

create table if not exists public.dashboard_control_runs (
  id uuid primary key,
  action text not null,
  requested_by text not null,
  status text not null check (status in ('queued','running','completed','failed','busy')),
  message text,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);
create index if not exists idx_dashboard_control_runs_started
  on public.dashboard_control_runs(started_at desc);
alter table public.dashboard_control_runs enable row level security;
revoke all on public.dashboard_control_runs from anon, authenticated;

create table if not exists public.dashboard_sync_lock (
  id integer primary key check (id = 1),
  locked_by text,
  lock_expires_at timestamptz,
  updated_at timestamptz not null default now()
);
alter table public.dashboard_sync_lock enable row level security;
revoke all on public.dashboard_sync_lock from anon, authenticated;
insert into public.dashboard_sync_lock(id) values (1)
on conflict (id) do nothing;

create or replace function public.claim_dashboard_sync_lock(p_owner text, p_lease_seconds integer default 3600)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare affected integer;
begin
  if p_owner is null or length(trim(p_owner)) = 0 then
    return false;
  end if;
  update public.dashboard_sync_lock
     set locked_by = p_owner,
         lock_expires_at = now() + make_interval(secs => least(greatest(coalesce(p_lease_seconds, 3600), 60), 3600)),
         updated_at = now()
   where id = 1
     and (locked_by is null or lock_expires_at is null or lock_expires_at < now() or locked_by = p_owner);
  get diagnostics affected = row_count;
  return affected = 1;
end;
$$;

create or replace function public.release_dashboard_sync_lock(p_owner text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare affected integer;
begin
  update public.dashboard_sync_lock
     set locked_by = null, lock_expires_at = null, updated_at = now()
   where id = 1 and locked_by = p_owner;
  get diagnostics affected = row_count;
  return affected = 1;
end;
$$;

revoke all on function public.claim_dashboard_sync_lock(text, integer) from public, anon, authenticated;
revoke all on function public.release_dashboard_sync_lock(text) from public, anon, authenticated;
grant execute on function public.claim_dashboard_sync_lock(text, integer) to service_role;
grant execute on function public.release_dashboard_sync_lock(text) to service_role;
